-- =============================================================================
-- Workshop-3 : Streaming ETL with Apache Kafka and Machine Learning
-- create_tables.sql : PostgreSQL schema (public) for the prediction database
--
-- Tables
--   raw_happiness_events  raw / staging table: every Kafka message exactly as it
--                         arrived, with its processing status (not a dimension)
--   dim_country           one row per country
--   dim_date              one row per historical year (2015-2019)
--   fact_predictions      one row per successfully predicted event
--
-- Conventions
--   * All timestamps are naive local time written by the Python scripts (the same
--     clock as event_time). There are no database-side time defaults, so event_time,
--     received_at and prediction_timestamp can be compared directly.
--   * prediction_error = actual_score - predicted_score (signed). The average
--     prediction error KPI should use ABS(prediction_error).
--   * The script can be run more than once: it only creates what is missing.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Dimension: country
-- The consumer adds a country the first time it appears in a valid event.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_country (
    country_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name  TEXT NOT NULL,
    CONSTRAINT uq_dim_country_name UNIQUE (country_name),
    CONSTRAINT ck_dim_country_name CHECK (length(trim(country_name)) > 0)
);


-- -----------------------------------------------------------------------------
-- Dimension: date
-- The key is the historical year of the observation (2015-2019): the time KPI
-- analyses the years of the report, not the technical moment of the event.
-- The consumer can validate the year of an event against this table.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_date (
    date_id  INTEGER PRIMARY KEY,
    year     INTEGER NOT NULL,
    CONSTRAINT uq_dim_date_year UNIQUE (year),
    CONSTRAINT ck_dim_date_year CHECK (date_id = year)
);

INSERT INTO dim_date (date_id, year) VALUES
    (2015, 2015),
    (2016, 2016),
    (2017, 2017),
    (2018, 2018),
    (2019, 2019)
ON CONFLICT DO NOTHING;


-- -----------------------------------------------------------------------------
-- Raw table: original Kafka messages
-- The consumer inserts every message BEFORE validating it (status RECEIVED) and
-- then updates the status. A row that stays in RECEIVED means the consumer
-- stopped in the middle of processing it.
--   raw_payload is TEXT (not JSONB) on purpose: it keeps the message exactly as
--   it arrived, including malformed JSON, which JSONB would reject or rewrite.
--   event_id is copied from the payload only when it can be read (traceability).
--   status_detail explains why an event is not VALID (e.g. "missing field: gdp").
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw_happiness_events (
    raw_event_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kafka_topic        TEXT      NOT NULL,
    kafka_partition    INTEGER   NOT NULL,
    kafka_offset       BIGINT    NOT NULL,
    kafka_key          TEXT,
    raw_payload        TEXT      NOT NULL,
    event_id           TEXT,
    processing_status  TEXT      NOT NULL DEFAULT 'RECEIVED',
    status_detail      TEXT,
    received_at        TIMESTAMP NOT NULL,
    processed_at       TIMESTAMP,
    -- the same Kafka record is never stored twice (re-reads after a restart or replay)
    CONSTRAINT uq_raw_kafka_position UNIQUE (kafka_topic, kafka_partition, kafka_offset),
    CONSTRAINT ck_raw_status CHECK (processing_status IN
        ('RECEIVED', 'VALID', 'INVALID_SCHEMA', 'INVALID_VALUES', 'PREDICTION_ERROR'))
);

CREATE INDEX IF NOT EXISTS ix_raw_event_id ON raw_happiness_events (event_id);
CREATE INDEX IF NOT EXISTS ix_raw_status   ON raw_happiness_events (processing_status);


-- -----------------------------------------------------------------------------
-- Fact table: predictions
-- Only events that passed validation and were predicted successfully.
-- raw_event_id links each prediction to the exact raw event that produced it,
-- and it is unique: one prediction per raw event.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS fact_predictions (
    prediction_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_event_id          BIGINT           NOT NULL,
    country_id            INTEGER          NOT NULL,
    date_id               INTEGER          NOT NULL,
    actual_score          DOUBLE PRECISION NOT NULL,
    predicted_score       DOUBLE PRECISION NOT NULL,
    prediction_error      DOUBLE PRECISION NOT NULL,
    event_time            TIMESTAMP        NOT NULL,
    prediction_timestamp  TIMESTAMP        NOT NULL,
    CONSTRAINT uq_fact_raw_event UNIQUE (raw_event_id),
    CONSTRAINT fk_fact_raw     FOREIGN KEY (raw_event_id) REFERENCES raw_happiness_events (raw_event_id),
    CONSTRAINT fk_fact_country FOREIGN KEY (country_id)   REFERENCES dim_country (country_id),
    CONSTRAINT fk_fact_date    FOREIGN KEY (date_id)      REFERENCES dim_date (date_id)
);

CREATE INDEX IF NOT EXISTS ix_fact_country ON fact_predictions (country_id);
CREATE INDEX IF NOT EXISTS ix_fact_date    ON fact_predictions (date_id);
